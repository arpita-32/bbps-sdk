import { HostTheme, TransactionRecord } from '../types/sdk';

export function formatCurrency(amount: number): string {
  return `₹${amount.toLocaleString('en-IN', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;
}

export function maskSensitiveValue(val: string, keepLast = 4): string {
  if (!val) return '';
  if (val.length <= keepLast) return val;
  return `${'X'.repeat(Math.max(4, val.length - keepLast))}${val.slice(-keepLast)}`;
}

